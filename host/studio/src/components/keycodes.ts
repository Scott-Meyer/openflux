/**
 * Every key code a key action can hold, grouped for the keycode picker, with the short legend a
 * key cap shows and a longer label. The names and aliases are the daemon's
 * (`host/daemon/tests/fixtures/keycodes.json`); `keycodes.test.tsx` keeps them in agreement.
 */

export interface KeycodeInfo {
  /** The `KC_*` name keymap documents use. */
  code: string;
  /** Short legend for a key cap, at most six characters. */
  legend: string;
  /** What the key does. */
  label: string;
}

export interface KeycodeCategory {
  label: string;
  keys: KeycodeInfo[];
}

const k = (code: string, legend: string, label: string = legend): KeycodeInfo => ({ code, legend, label });

const range = (n: number, f: (i: number) => KeycodeInfo): KeycodeInfo[] => Array.from({ length: n }, (_, i) => f(i));

