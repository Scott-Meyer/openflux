const BY_CODE = new Map(KEYCODE_CATEGORIES.flatMap((c) => c.keys).map((key) => [key.code, key]));

/** The name a key code stands for: itself, or the name an alias stands for. */
export function canonicalKeycode(code: string): string {
  return KEYCODE_ALIASES[code] ?? code;
}

/** What Studio knows about a key code or alias, or undefined for a name it doesn't know. */
export function keycodeInfo(code: string): KeycodeInfo | undefined {
  return BY_CODE.get(canonicalKeycode(code));
}

/** The legend a key cap shows for a key code: its short legend, or the name without `KC_`. */
export function keycodeLegend(code: string): string {
  return keycodeInfo(code)?.legend ?? code.replace(/^KC_/, "");
}
