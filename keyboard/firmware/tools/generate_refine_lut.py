"""Regenerate the fixed-point activation tables (no model data or dependencies)."""

import argparse
from decimal import Decimal, localcontext
from pathlib import Path


HEADER = Path(__file__).resolve().parents[1] / "src" / "fw_refine_lut.h"


def generate_header() -> str:
    # Samples at [-8,+8] in steps of 1/32. Round to the nearest Q15 value,
    # saturating symmetrically so reflecting a tanh value cannot overflow.
    sigmoid, tanh = [], []
    with localcontext() as ctx:
        ctx.prec = 64
        for i in range(-256, 257):
            x = Decimal(i) / 32
            e = (-x).exp()
            for result, value in [
                (sigmoid, 1 / (1 + e)),
                (tanh, (1 - e * e) / (1 + e * e)),
            ]:
                result.append(max(-32767, min(32767, round(32768 * value))))

    lines = [
        "/* Generated by keyboard/firmware/tools/generate_refine_lut.py. */",
        "#ifndef FW_REFINE_LUT_H",
        "#define FW_REFINE_LUT_H",
        "",
        '#include "fw_scan_hot.h"',
        "#include <stdint.h>",
        "",
        "// clang-format off",
    ]
    for name, table in [("sigmoid", sigmoid), ("tanh", tanh)]:
        lines.append(f"static const int16_t FW_SCAN_TABLE({name}_q15)[513] = {{")
        for start in range(0, len(table), 14):
            lines.append(
                "    " + ", ".join(str(x) for x in table[start : start + 14]) + ","
            )
        lines.append("};")
    return "\n".join(
        [*lines, "// clang-format on", "", "#endif /* FW_REFINE_LUT_H */", ""]
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if the checked-in table is stale"
    )
    args = parser.parse_args()
    result = generate_header()
    if args.check:
        if result != HEADER.read_text():
            raise SystemExit(f"{HEADER}: regenerate using {Path(__file__).name}")
    else:
        HEADER.write_text(result)
