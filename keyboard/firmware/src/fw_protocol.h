#ifndef FW_PROTOCOL_H
#define FW_PROTOCOL_H

#include <stdint.h>

#define FW_USB_VID         0x3761U
#define FW_USB_PID         0x4015U
#define FW_USB_PACKET_SIZE 64U
/* Set by the build from KEYGLASS_FIRMWARE_VERSION in CMakeLists.txt. */
#ifndef FW_PROJECT_VERSION
#error "FW_PROJECT_VERSION must be defined by the build"
#endif
#define FW_VERSION_STR "keyglass-firmware " FW_PROJECT_VERSION

#define FW_NUM_SENSORS   160U
#define FW_NUM_BANKS     10U
#define FW_COLS_PER_BANK 16U

/* RP2040 GPIO pinout */
#define FW_UART_TX_GPIO 8U
#define FW_UART_RX_GPIO 9U
#define FW_UART_BAUD    921600U

#define FW_SOC_AUX_GPIO 3U
#define FW_SOC_PWR_GPIO 4U
#define FW_SOC_RST_GPIO 5U

#define FW_ADC_GPIO     29U
#define FW_ADC_CHANNEL  3U
#define FW_MUX_COL_MASK 0x0003FC00U /* GPIO 10..17 */

/* LittleFS flash partition (top 1 MiB of 16 MiB flash) */
#define FW_FLASH_SIZE_BYTES (16U * 1024U * 1024U)
#define FW_LFS_OFFSET_BYTES 0x00F00000U
#define FW_LFS_BLOCK_SIZE   4096U
#define FW_LFS_BLOCK_COUNT  256U

enum fw_usb_cmd {
    FW_CMD_REQUEST_VERSION = 0x01,
    FW_CMD_SEND_KEYMAP = 0x64,
    FW_CMD_MCU_BOOTLOADER = 0x65,
    FW_CMD_SOC_BOOTLOADER = 0x66,
    FW_CMD_GET_KEYMAP = 0x67,
    FW_CMD_SET_LANGUAGE = 0x68,
    FW_CMD_SET_PLATFORM = 0x69,
    FW_CMD_SET_ACTIVE_PROFILE = 0x6A,
    FW_CMD_FILE_FROM_HOST = 0x6B,
    FW_CMD_FILE_TO_HOST = 0x6C,
    FW_CMD_GET_RUNTIME_STATE = 0x6D,
    FW_CMD_PRESS_REFINEMENT_STATUS = 0x70,
    FW_CMD_PUT_PRESS_REFINEMENT = 0x71,
    FW_CMD_GET_PRESS_REFINEMENT = 0x72,
    FW_CMD_PUT_VIAL_DEF = 0x73,
    FW_CMD_SET_GAMEPAD_CONFIG = 0x74,
    FW_CMD_SET_LAYER_OVERRIDE = 0x75,
};

enum fw_resp_type {
    FW_RESP_NAK = 0,
    FW_RESP_ACK = 1,
};

enum fw_uart_msg_type {
    FW_UART_MSG_ACK = 0,
    FW_UART_MSG_NAK = 1,
    FW_UART_MSG_UPDATE = 2,
    FW_UART_MSG_QC_SENSORS = 3,
    FW_UART_MSG_ANALOG = 4,
    FW_UART_MSG_FLUX_ACTION = 5,
    FW_UART_MSG_RESOLVED_KEYS = 6,
};

#define FW_UART_MSG_UPDATE_LEN     139U
#define FW_UART_MSG_QC_LEN         401U
#define FW_UART_ANALOG_MAX_ENTRIES 32U
#define FW_UART_MSG_ANALOG_HDR_LEN 10U
#define FW_UART_MSG_ANALOG_ENT_LEN 5U
#define FW_UART_MSG_ANALOG_MAX_LEN (FW_UART_MSG_ANALOG_HDR_LEN + FW_UART_ANALOG_MAX_ENTRIES * FW_UART_MSG_ANALOG_ENT_LEN)

/* Bridge -> firmware UART response byte 2 flags */
#define FW_UART_FLAG_QC_MODE     0x01U
#define FW_UART_FLAG_ANALOG_MODE 0x02U

enum fw_of_func_code {
    FW_OF_FUNC_TRANSPARENT = 0x00,
    FW_OF_FUNC_BRIGHTNESS_UP = 0x02,
    FW_OF_FUNC_BRIGHTNESS_DOWN = 0x03,
    FW_OF_FUNC_PROFILE_CYCLE_NEXT = 0x04,
    FW_OF_FUNC_PROFILE_CYCLE_PREV = 0x05,
    FW_OF_FUNC_ACTUATION_MODE_NEXT = 0x06,
    FW_OF_FUNC_ACTUATION_MODE_PREV = 0x07,
    FW_OF_FUNC_PLATFORM_LINUX = 0x08,
    FW_OF_FUNC_PLATFORM_MACOS = 0x09,
    FW_OF_FUNC_PLATFORM_WINDOWS = 0x0A,
    FW_OF_FUNC_AUTO_PROFILE_LOCK = 0x0B,
    FW_OF_FUNC_START_PAUSE_POMODORO = 0x0C,
    FW_OF_FUNC_RESET_POMODORO = 0x0D,
    FW_OF_FUNC_THEME_CYCLE_NEXT = 0x0E,
    FW_OF_FUNC_THEME_CYCLE_PREV = 0x0F,
};

#define FW_CALIB_MAGIC      0xFAC5CA1EU
#define FW_CALIB_DEFAULT_Q8 0x0100U

#endif /* FW_PROTOCOL_H */
